#!/usr/bin/env bash
set -euo pipefail

BASE_URL="${BASE_URL:-http://127.0.0.1:9999}"
WORK_DIR="${WORK_DIR:-/tmp/tsukuyomi-bench-$(date +%s)}"
RUN_SMOKE="${RUN_SMOKE:-1}"
RUN_ACCEPTANCE="${RUN_ACCEPTANCE:-1}"
SMOKE_AUTO_START="${SMOKE_AUTO_START:-0}"
SMOKE_SERVER_CMD="${SMOKE_SERVER_CMD:-}"
REQUEST_TIMEOUT="${REQUEST_TIMEOUT:-30}"

REPORT_MD="${WORK_DIR}/benchmark-report.md"

RED="$(printf '\033[31m')"
GREEN="$(printf '\033[32m')"
YELLOW="$(printf '\033[33m')"
BOLD="$(printf '\033[1m')"
RESET="$(printf '\033[0m')"

log_step() {
  printf '%s==>%s %s\n' "${BOLD}" "${RESET}" "$1"
}

pass() {
  printf '%sPASS%s %s\n' "${GREEN}" "${RESET}" "$1"
}

warn() {
  printf '%sWARN%s %s\n' "${YELLOW}" "${RESET}" "$1"
}

fail() {
  printf '%sFAIL%s %s\n' "${RED}" "${RESET}" "$1"
  exit 1
}

usage() {
  cat <<EOF
Usage:
  scripts/benchmark_validation_runner.sh [--base-url <url>] [--work-dir <dir>] [--no-smoke] [--no-acceptance]
                                        [--auto-start-smoke --smoke-server-cmd "<cmd>"]

Environment overrides:
  BASE_URL          Default: http://127.0.0.1:9999
  WORK_DIR          Default: /tmp/tsukuyomi-bench-<timestamp>
  RUN_SMOKE         1/0 (default 1)
  RUN_ACCEPTANCE    1/0 (default 1)
  SMOKE_AUTO_START  1/0 (default 0)
  SMOKE_SERVER_CMD  required when SMOKE_AUTO_START=1
  REQUEST_TIMEOUT   Default: 30

Examples:
  scripts/benchmark_validation_runner.sh
  scripts/benchmark_validation_runner.sh --base-url http://127.0.0.1:9999
  scripts/benchmark_validation_runner.sh --auto-start-smoke --smoke-server-cmd "tsukuyomi start --config ~/.local/share/tsukuyomi/config/corelaw.json"
EOF
}

require_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    fail "Missing required command: $1"
  fi
}

parse_args() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --help|-h)
        usage
        exit 0
        ;;
      --base-url)
        BASE_URL="$2"
        shift 2
        ;;
      --work-dir)
        WORK_DIR="$2"
        shift 2
        ;;
      --no-smoke)
        RUN_SMOKE=0
        shift
        ;;
      --no-acceptance)
        RUN_ACCEPTANCE=0
        shift
        ;;
      --auto-start-smoke)
        SMOKE_AUTO_START=1
        shift
        ;;
      --smoke-server-cmd)
        SMOKE_SERVER_CMD="$2"
        shift 2
        ;;
      *)
        fail "Unknown argument: $1 (use --help)"
        ;;
    esac
  done
}

run_smoke() {
  local smoke_log="${WORK_DIR}/smoke.log"
  if [[ "${RUN_SMOKE}" != "1" ]]; then
    warn "Smoke run disabled."
    return 0
  fi
  log_step "Running smoke scenarios"
  if [[ "${SMOKE_AUTO_START}" == "1" ]]; then
    [[ -n "${SMOKE_SERVER_CMD}" ]] || fail "SMOKE_AUTO_START=1 requires SMOKE_SERVER_CMD"
    if BASE_URL="${BASE_URL}" REQUEST_TIMEOUT="${REQUEST_TIMEOUT}" AUTO_START=1 SERVER_CMD="${SMOKE_SERVER_CMD}" \
      /workspace/scripts/smoke_test.sh >"${smoke_log}" 2>&1; then
      pass "Smoke scenarios passed."
    else
      warn "Smoke scenarios reported failure. See ${smoke_log}"
      return 1
    fi
  else
    if BASE_URL="${BASE_URL}" REQUEST_TIMEOUT="${REQUEST_TIMEOUT}" /workspace/scripts/smoke_test.sh >"${smoke_log}" 2>&1; then
      pass "Smoke scenarios passed."
    else
      warn "Smoke scenarios reported failure. See ${smoke_log}"
      return 1
    fi
  fi
}

run_acceptance() {
  local acceptance_log="${WORK_DIR}/acceptance.log"
  if [[ "${RUN_ACCEPTANCE}" != "1" ]]; then
    warn "Acceptance gate disabled."
    return 0
  fi
  log_step "Running acceptance gate"
  if RUN_SMOKE=0 /workspace/scripts/acceptance_gate.sh >"${acceptance_log}" 2>&1; then
    pass "Acceptance gate passed."
  else
    warn "Acceptance gate failed. See ${acceptance_log}"
    return 1
  fi
}

generate_report() {
  local commit_hash
  commit_hash="$(git rev-parse --short HEAD)"
  cat > "${REPORT_MD}" <<EOF
# Tsukuyomi Benchmark Validation Report

- Generated: $(date -u +"%Y-%m-%dT%H:%M:%SZ")
- Commit: \`${commit_hash}\`
- Base URL: \`${BASE_URL}\`

## Scenario execution summary

- Smoke scenarios: $([[ "${RUN_SMOKE}" == "1" ]] && echo "executed" || echo "skipped")
- Acceptance gate: $([[ "${RUN_ACCEPTANCE}" == "1" ]] && echo "executed" || echo "skipped")

## Artifact files

- smoke log: \`${WORK_DIR}/smoke.log\`
- acceptance log: \`${WORK_DIR}/acceptance.log\`

## Notes

- This report is generated by \`scripts/benchmark_validation_runner.sh\`.
- For detailed scenario definitions, see \`docs/benchmarks/VALIDATION_SCENARIOS.md\`.
EOF
}

main() {
  parse_args "$@"
  require_cmd bash
  require_cmd curl
  require_cmd jq
  require_cmd python3
  require_cmd git

  mkdir -p "${WORK_DIR}"
  log_step "Benchmark workspace: ${WORK_DIR}"

  local rc=0
  run_smoke || rc=1
  run_acceptance || rc=1
  generate_report

  if [[ ${rc} -eq 0 ]]; then
    pass "Benchmark validation completed successfully."
  else
    warn "Benchmark validation completed with failures."
  fi
  printf 'Report: %s\n' "${REPORT_MD}"
  return ${rc}
}

main "$@"
